"""Split pristine PolyBench kernels and harnesses and add conditional AXI ports."""
import argparse
from pathlib import Path
import re
import subprocess

SUITE = Path(__file__).resolve().parent
UPSTREAM_COMMIT = 'd3a15bb1725afaaa33bcf3a4db6087ebf557c9b8'
PATHS = {
    'gemm': 'linear-algebra/blas/gemm',
    'atax': 'linear-algebra/kernels/atax',
    'bicg': 'linear-algebra/kernels/bicg',
    'mvt': 'linear-algebra/kernels/mvt',
    'trisolv': 'linear-algebra/solvers/trisolv',
    'jacobi-1d': 'stencils/jacobi-1d',
    'jacobi-2d': 'stencils/jacobi-2d',
    'floyd-warshall': 'medley/floyd-warshall',
}
BANNER = '/* Generated by polybench/prepare.py from the pinned original distribution.\n * Edit the generator, not this file. Upstream notices are retained below.\n */\n'


def generate(name, source):
    """Only the pinned distribution layout is supported; fail on unexpected input."""
    directory = source / PATHS[name]
    original = (directory / (name + '.c')).read_text()
    top = 'kernel_' + name.replace('-', '_')
    match = re.search(r'^static\n(void ' + re.escape(top) + r'\([\s\S]*?\))\n\{[\s\S]*?^\}',
                      original, flags=re.M)
    if not match:
        raise ValueError('Cannot identify complete kernel ' + name)
    signature = match.group(1)
    ports = re.findall(r'POLYBENCH_[123]D\(\s*(\w+)', signature)
    if not ports:
        raise ValueError('No array parameters in ' + name)
    pragmas = '#ifdef USE_AXI\n' + ''.join(
        '#pragma HLS interface port=' + port + ' mode=m_axi offset=direct\n' for port in ports) + '#endif\n'
    prelude = original[:original.index('/* Array initialization. */')]
    kernel = prelude + pragmas + original[match.start() + len('static\n'):match.end()] + '\n'
    # Initialization, printing, allocation, top invocation and cleanup are unchanged.
    harness = original[:match.start()] + original[match.end():]
    header = (directory / (name + '.h')).read_text()
    guard = header.rfind('#endif')
    if guard < 0:
        raise ValueError('Missing header guard in ' + name)
    header = header[:guard] + signature + ';\n\n' + header[guard:]
    return {name + '.c': BANNER + kernel, name + '.h': BANNER + header,
            'tb_' + name + '.c': BANNER + harness}


def prepare(check=False):
    source = SUITE / 'sources'
    if not (source / 'utilities/polybench.h').is_file():
        raise ValueError('Initialize PolyBench with: git submodule update --init polybench/sources')
    revision = subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip()
    if revision != UPSTREAM_COMMIT:
        raise ValueError('PolyBench must be at the pinned commit ' + UPSTREAM_COMMIT)
    if subprocess.check_output(['git', '-C', str(source), 'status', '--porcelain', '--untracked-files=no']):
        raise ValueError('PolyBench source submodule has local changes; restore the pinned sources first')
    count = 0
    for name in PATHS:
        target = SUITE / 'build/adapters' / name
        for filename, content in generate(name, source).items():
            output = target / filename
            if check:
                if not output.is_file() or output.read_text() != content:
                    raise ValueError('Regenerate adapters: python3 polybench/prepare.py')
            else:
                target.mkdir(parents=True, exist_ok=True)
                output.write_text(content)
            count += 1
    return count


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    print(('Verified' if args.check else 'Prepared'), prepare(args.check), 'PolyBench adapter files.')
